        var left = Math.max(16, Math.min(rect.left + rect.width / 2 - width / 2, window.innerWidth - width - 16));
        var top = rect.top - height - 12;
        if (top < 12) { top = rect.bottom + 12; credentialTip.classList.add('below'); }
